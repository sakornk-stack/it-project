// Arrow-key movement along a row of tabs (WAI-ARIA tabs pattern): Left/Right step
// and wrap around, Home/End jump to the ends. Any other key returns null.
export function nextTabIndex(current: number, key: string, count: number): number | null {
  if (count <= 0) return null;
  switch (key) {
    case 'ArrowRight':
      return (current + 1) % count;
    case 'ArrowLeft':
      return (current - 1 + count) % count;
    case 'Home':
      return 0;
    case 'End':
      return count - 1;
    default:
      return null;
  }
}
